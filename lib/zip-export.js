/**
 * Zero-dependency ZIP archive builder (Store method 0 with standard IEEE 802.3 CRC-32).
 * Works cleanly in both browser Blob downloads and Node.js tests.
 */

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let i = 0; i < 256; i++) {
    let c = i;
    for (let k = 0; k < 8; k++) {
      c = (c & 1) !== 0 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    table[i] = c >>> 0;
  }
  return table;
})();

function crc32(bytes) {
  let crc = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) {
    crc = CRC_TABLE[(crc ^ bytes[i]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function sanitizeZipEntryName(name) {
  return String(name || 'file.txt')
    .replace(/\\/g, '/')
    .replace(/^\/+/, '')
    .split('/')
    .filter((seg) => seg && seg !== '.' && seg !== '..')
    .join('/');
}

export function buildZipBytes(files) {
  const encoder = new TextEncoder();
  const localParts = [];
  const centralParts = [];
  let offset = 0;

  for (const file of files) {
    const safeName = sanitizeZipEntryName(file.name);
    if (!safeName) continue;
    const nameBytes = encoder.encode(safeName);
    const dataBytes = typeof file.content === 'string' ? encoder.encode(file.content) : new Uint8Array(file.content);
    const sum = crc32(dataBytes);
    const size = dataBytes.length;

    // Local file header (30 bytes + filename)
    const localHeader = new Uint8Array(30 + nameBytes.length);
    const lv = new DataView(localHeader.buffer);
    lv.setUint32(0, 0x04034b50, true); // Local file header signature
    lv.setUint16(4, 20, true); // Version needed
    lv.setUint16(6, 0x0800, true); // UTF-8 flag
    lv.setUint16(8, 0, true); // Compression: Store (0)
    lv.setUint16(10, 0, true);
    lv.setUint16(12, 0, true);
    lv.setUint32(14, sum, true);
    lv.setUint32(18, size, true);
    lv.setUint32(22, size, true);
    lv.setUint16(26, nameBytes.length, true);
    lv.setUint16(28, 0, true);
    localHeader.set(nameBytes, 30);

    localParts.push(localHeader, dataBytes);

    // Central directory header (46 bytes + filename)
    const centralHeader = new Uint8Array(46 + nameBytes.length);
    const cv = new DataView(centralHeader.buffer);
    cv.setUint32(0, 0x02014b50, true);
    cv.setUint16(4, 20, true);
    cv.setUint16(6, 20, true);
    cv.setUint16(8, 0x0800, true);
    cv.setUint16(10, 0, true);
    cv.setUint16(12, 0, true);
    cv.setUint16(14, 0, true);
    cv.setUint32(16, sum, true);
    cv.setUint32(20, size, true);
    cv.setUint32(24, size, true);
    cv.setUint16(28, nameBytes.length, true);
    cv.setUint16(30, 0, true);
    cv.setUint16(32, 0, true);
    cv.setUint16(34, 0, true);
    cv.setUint16(36, 0, true);
    cv.setUint32(38, 0, true);
    cv.setUint32(42, offset, true);
    centralHeader.set(nameBytes, 46);

    centralParts.push(centralHeader);
    offset += localHeader.length + size;
  }

  let centralSize = 0;
  for (const part of centralParts) centralSize += part.length;

  const endRecord = new Uint8Array(22);
  const ev = new DataView(endRecord.buffer);
  ev.setUint32(0, 0x06054b50, true);
  ev.setUint16(4, 0, true);
  ev.setUint16(6, 0, true);
  ev.setUint16(8, centralParts.length, true);
  ev.setUint16(10, centralParts.length, true);
  ev.setUint32(12, centralSize, true);
  ev.setUint32(16, offset, true);
  ev.setUint16(20, 0, true);

  const totalLength = offset + centralSize + endRecord.length;
  const archive = new Uint8Array(totalLength);
  let cursor = 0;
  for (const p of localParts) {
    archive.set(p, cursor);
    cursor += p.length;
  }
  for (const p of centralParts) {
    archive.set(p, cursor);
    cursor += p.length;
  }
  archive.set(endRecord, cursor);
  return archive;
}

export function buildJavaProjectFiles({
  javaCode,
  junitCode,
  pythonCode = '',
  javaVersion = '17',
  verificationReport = null,
}) {
  const safeVer = String(javaVersion).replace(/[^0-9]/g, '') || '17';
  const pomXml = `<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0"
         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd">
    <modelVersion>4.0.0</modelVersion>
    <groupId>com.jforge</groupId>
    <artifactId>ciap-migrated-project</artifactId>
    <version>1.0.0</version>
    <properties>
        <maven.compiler.source>${safeVer}</maven.compiler.source>
        <maven.compiler.target>${safeVer}</maven.compiler.target>
        <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
    </properties>
    <dependencies>
        <dependency>
            <groupId>org.junit.jupiter</groupId>
            <artifactId>junit-jupiter</artifactId>
            <version>5.10.2</version>
            <scope>test</scope>
        </dependency>
    </dependencies>
</project>
`;

  const readme = `# J-Forge Migrated Java ${safeVer} Project

Generated by J-Forge Studio.

## Structure
- \`src/main/java/com/jforge/ciap/Solution.java\` — Migrated Java implementation
- \`src/test/java/com/jforge/ciap/SolutionTest.java\` — JUnit 5 verification tests
- \`pom.xml\` — Maven configuration (Java ${safeVer})
- \`verification-report.json\` — Execution & verification record

## Run with Maven
\`\`\`bash
mvn test
\`\`\`
`;

  const reportJson = JSON.stringify(
    verificationReport || {
      status: 'not_verified',
      note: 'Run Convert & Verify in J-Forge Studio to attach live CPython vs OpenJDK verification results.',
    },
    null,
    2
  );

  return [
    { name: 'pom.xml', content: pomXml },
    { name: 'README.md', content: readme },
    { name: 'src/main/java/com/jforge/ciap/Solution.java', content: javaCode || '// Empty' },
    { name: 'src/test/java/com/jforge/ciap/SolutionTest.java', content: junitCode || '// Empty' },
    ...(pythonCode ? [{ name: 'source/original.py', content: pythonCode }] : []),
    { name: 'verification-report.json', content: reportJson },
  ];
}
